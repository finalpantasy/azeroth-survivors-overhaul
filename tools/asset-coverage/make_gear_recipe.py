#!/usr/bin/env python3
"""Build an as-recipe/1 recipe (plus its single-file converter tool) for a cumulative set of gear batches.

The converter is generated as ONE self-contained script (the repo's rigid converter, gear_batch and the item spec are embedded) so it can be
registered in installer tools/registry.json with a pinned SHA-256 and run as `--source-dir {in:src} --output-dir {out}`, like rigid-converter.
This maintainer tool needs the local Retail cache (analysis/asset-coverage/work/cache-items), the listfile and a game install; the recipe
it writes needs none of that: it only names FileDataIDs + hashes, and the installer exports them from the owner's own client.

  make_gear_recipe.py --id retail-gear-r1-starter --title "..." --description "..." --tag r1 \
      --build analysis/asset-coverage/gear/r1-build3 --picks analysis/asset-coverage/gear/picks-r1.json [--build ... --picks ...]
Writes analysis/asset-coverage/recipes/<id>.json, recipes/tools/gear_step_<tag>.py and a registry snippet.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
PROJECT = HERE.parents[1]
WORK = PROJECT / "analysis" / "asset-coverage" / "work"
RECIPES = PROJECT / "analysis" / "asset-coverage" / "recipes"
META = PROJECT / "analysis" / "asset-coverage" / "recipes-meta"      # tools, registry snippets, summaries (kept out of the recipe folder)
sys.path.insert(0, str(PROJECT / "tools" / "installer"))
from asinstall.dbc import Dbc  # noqa: E402

spec = importlib.util.spec_from_file_location("ric", HERE / "rigid_item_convert.py")
ric = importlib.util.module_from_spec(spec)
sys.modules["ric"] = ric
spec.loader.exec_module(ric)

INSPECT = PROJECT / "tools" / "mpq-inspect.exe"
DBC_PATH = "DBFilesClient\\ItemDisplayInfo.dbc"
OFFICIAL_DBC_SHA = "6f37ca862dc632a11aaf86e0ba7b183aa7abaebb052549e6120aa9fa69dd9dee"
MACE = {"display": 5194, "column": 1, "new_basename": "KultirasQuestB01_Silver_Static.mdx"}
EXE_SHAS = ["6382e9ae654295293b82d48fb07a1aa999132775bda10c6c6f80d973d2c1ddfb", "524e83499dd8f216fadddf75c57346d03dcecb0b456b1f07f87eb6b109c35a1b"]

STEP_TEMPLATE = r'''#!/usr/bin/env python3
"""Self-contained gear converter step (generated by make_gear_recipe.py; do not edit: the installer pins this file's SHA-256).

Reads the CASC export folder (model-<fdid>.m2, skin-<fdid>.skin, texture-<fdid>.blp), converts every item in the embedded spec to a rigid
MD20 v256 model (uniform scale, shield turn, relaxations recorded in the spec) and writes <out>/payload/Item/ObjectComponents/... .
"""
import argparse, json, shutil, sys, tempfile, types
from pathlib import Path

SOURCES = __SOURCES__
SPEC = __SPEC__


def _load(name, code):
    mod = types.ModuleType(name)
    mod.__file__ = name + ".py"
    sys.modules[name] = mod
    exec(compile(code, name, "exec"), mod.__dict__)
    return mod


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--source-dir", type=Path, required=True)
    ap.add_argument("--output-dir", type=Path, required=True)
    ap.add_argument("--packer")
    a = ap.parse_args()
    _load("build_retail_rigid_base", SOURCES["base"])
    ric = _load("ric", SOURCES["ric"])
    batch = _load("gear_batch_embedded", SOURCES["batch"])
    ric.fetch = lambda *args, **kw: None            # inputs are already exported
    cache = Path(tempfile.mkdtemp(prefix="gearcache-"))
    try:
        for f in a.source_dir.iterdir():
            if f.is_file() and "-" in f.name:
                fdid = f.name.split("-", 1)[1].split(".", 1)[0]
                if fdid.isdigit():
                    shutil.copyfile(f, cache / f"{fdid}.bin")
        payload = a.output_dir / "payload"
        payload.mkdir(parents=True, exist_ok=True)
        results = []
        for item in SPEC["items"]:
            r = batch.convert_one(item, cache, Path("no-listfile"), "retail", payload)
            results.append({"id": item["id"], **{k: r[k] for k in ("verts", "tris", "model_bytes", "texture_bytes", "scale")}})
        (a.output_dir / "report.json").write_text(json.dumps(results, indent=1), encoding="utf8")
        print(json.dumps({"items": len(results), "tris": sum(r["tris"] for r in results)}))
    finally:
        shutil.rmtree(cache, ignore_errors=True)


if __name__ == "__main__":
    main()
'''


def sha(b):
    return hashlib.sha256(b).hexdigest()


def read_cache(fdid):
    return (WORK / "cache-items" / f"{fdid}.bin").read_bytes()


def official_dbc():
    out = Path(tempfile.mkdtemp()) / "idi.dbc"
    found = None
    for name in ["patch.MPQ"] + [f"patch-{i}.MPQ" for i in range(2, 9)]:
        r = subprocess.run([str(INSPECT), str(PROJECT / "Data" / name), "extract", DBC_PATH, str(out)], capture_output=True, text=True)
        if r.returncode == 0 and out.is_file():
            found = out.read_bytes()
            out.unlink()
    if not found or sha(found) != OFFICIAL_DBC_SHA:
        raise SystemExit("official ItemDisplayInfo.dbc not reproduced from the game chain")
    return found


def embed_sources():
    base = (PROJECT / "tools" / "retail-rigid-preview" / "build_retail_rigid.py").read_text(encoding="utf8")
    r = (HERE / "rigid_item_convert.py").read_text(encoding="utf8")
    start = r.index("def _load_base():")
    end = r.index("B = _load_base()") + len("B = _load_base()")
    r = r[:start] + 'B = sys.modules["build_retail_rigid_base"]' + r[end:]
    b = (HERE / "gear_batch.py").read_text(encoding="utf8")
    start = b.index("HERE = Path(__file__).resolve().parent")
    end = b.index("ric = importlib.util.module_from_spec(spec)")
    end = b.index("spec.loader.exec_module(ric)") + len("spec.loader.exec_module(ric)")
    b = b[:start] + 'ric = sys.modules["ric"]' + b[end:]
    return {"base": base.replace("\r\n", "\n"), "ric": r.replace("\r\n", "\n"), "batch": b.replace("\r\n", "\n")}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--id", required=True)
    ap.add_argument("--tag", required=True)
    ap.add_argument("--title", required=True)
    ap.add_argument("--description", required=True)
    ap.add_argument("--build", type=Path, action="append", required=True)
    ap.add_argument("--picks", type=Path, action="append", required=True)
    ap.add_argument("--scales", type=Path, action="append", default=[], help="scales.json used when the builds were made (exact scale values)")
    ap.add_argument("--no-mace", action="store_true")
    a = ap.parse_args()
    listfile = WORK / "listfile-filtered.csv"
    cache = WORK / "cache-items"
    mace_cat = json.loads((PROJECT / "tools" / "local-asset-builder" / "retail-mace-silver.json").read_text("utf-8"))

    picks = {}
    for p in a.picks:
        for it in json.loads(p.read_text(encoding="utf8"))["items"]:
            picks[it["id"]] = it
    exact, exact_off = {}, {}
    for sp in a.scales:
        for k, v in json.loads(sp.read_text(encoding="utf8")).items():
            if v.get("scale"):
                exact[k] = max(0.45, min(1.3, v["scale"]))
            if v.get("offset"):
                exact_off[k] = v["offset"]
    spec_items, payload_files, edits, casc = [], {}, {}, {}
    totals = {"items": 0, "verts": 0, "tris": 0, "model_bytes": 0, "texture_bytes": 0, "max_tris": 0}
    for b in a.build:
        b = b.resolve()
        rep = json.loads((b / "gear-report.json").read_text(encoding="utf8"))["results"]
        for e in json.loads((b / "display-edits.json").read_text(encoding="utf8")):
            edits[(e["display"], e["column"])] = e
        for r in rep:
            if not r["ok"]:
                continue
            it = dict(picks[r["id"]])
            model = read_cache(r["model_fdid"])
            skin = read_cache(r["skin_fdid"])
            info = ric.inspect(model, skin, True, True, True, True)
            slots = ric.derive_textures(info, {}, ric.make_listfile_pick(listfile, r["model_fdid"]))
            spec_items.append({"id": r["id"], "kind": r["kind"], "name": r["name"], "fdid": r["model_fdid"], "tex": {str(s): f for s, f in slots.items()},
                               "tex_stem": it.get("tex_stem", r["name"]), "scale": exact.get(r["id"], r.get("scale", 1.0)),
                               "offset": exact_off.get(r["id"], r.get("offset"))})
            for fd, role, ext in [(r["model_fdid"], "model", "m2"), (r["skin_fdid"], "first-nonzero-SFID-skin", "skin")] + \
                                 [(t["fdid"], "item-texture", "blp") for t in r["textures"]]:
                data = read_cache(fd)
                casc[fd] = {"file_data_id": fd, "name": f"{'model' if ext == 'm2' else 'skin' if ext == 'skin' else 'texture'}-{fd}.{ext}",
                            "role": role, "bytes": len(data), "sha256": sha(data)}
            for f in (b / "payload").rglob("*"):
                pass
            totals["items"] += 1
            totals["verts"] += r["verts"]
            totals["tris"] += r["tris"]
            totals["model_bytes"] += r["model_bytes"]
            totals["texture_bytes"] += r["texture_bytes"]
            totals["max_tris"] = max(totals["max_tris"], r["tris"])
        for f in (b / "payload").rglob("*"):
            if f.is_file():
                payload_files["payload/" + f.relative_to(b / "payload").as_posix()] = f.read_bytes()
    if not a.no_mace:
        edits[(MACE["display"], MACE["column"])] = {"display": 5194, "column": 1, "new_basename": MACE["new_basename"], "kind": "Weapon", "id": "kultiras-mace"}

    # tool script
    tools_dir = META / "tools"
    tools_dir.mkdir(parents=True, exist_ok=True)
    script = STEP_TEMPLATE.replace("__SOURCES__", repr(embed_sources())).replace("__SPEC__", repr({"items": spec_items}))
    script_path = tools_dir / f"gear_step_{a.tag}.py"
    script_path.write_text(script, encoding="utf8", newline="\n")
    tool_sha = sha(script_path.read_bytes())

    # reproduce the payload through the generated tool from a synthetic export folder
    tmp = Path(tempfile.mkdtemp(prefix="gearrepro-"))
    (tmp / "src").mkdir()
    for c in casc.values():
        (tmp / "src" / c["name"]).write_bytes(read_cache(c["file_data_id"]))
    r = subprocess.run([sys.executable, "-I", str(script_path), "--source-dir", str(tmp / "src"), "--output-dir", str(tmp / "out")], capture_output=True, text=True)
    if r.returncode:
        raise SystemExit("tool run failed: " + r.stderr[-800:])
    for rel, data in payload_files.items():
        got = (tmp / "out" / rel).read_bytes()
        if got != data:
            raise SystemExit(f"tool output differs from the verified build for {rel}")
    extra = {p.relative_to(tmp / "out").as_posix() for p in (tmp / "out" / "payload").rglob("*") if p.is_file()} - set(payload_files)
    if extra:
        raise SystemExit(f"tool wrote unexpected files: {sorted(extra)[:5]}")

    # DBC edits on the official base
    base = official_dbc()
    dbc = Dbc(base, "ItemDisplayInfo.dbc")
    dbc_edits = []
    for (disp, col), e in sorted(edits.items()):
        before = dbc.get_string(disp, col)
        if not before:
            raise SystemExit(f"display {disp} column {col} is empty in the official DBC")
        dbc_edits.append({"row_id": disp, "column": col, "type": "string", "expect_before": before, "value": e["new_basename"]})
        dbc.set_string(disp, col, e["new_basename"])
    dbc_bytes = dbc.tobytes()
    dbc_sha = sha(dbc_bytes)

    retail = {"kind": "casc", "product": mace_cat["product"], "version": mace_cat["version"], "build_number": mace_cat["build_number"],
              "build_key": mace_cat["build_key"], "cdn_key": mace_cat["cdn_key"], "locale": "enUS", "build_config": mace_cat["build_config"],
              "cdn_config": mace_cat["cdn_config"], "files": [casc[k] for k in sorted(casc)],
              "note": "FileDataIDs picked by eye from offline contact sheets; item-ID mapping is not reproduced"}
    mpq_files = [{"slot": "patch-0.MPQ", "path": DBC_PATH, "from": "dbc:DBFilesClient/ItemDisplayInfo.dbc", "sha256": dbc_sha}]
    acceptance = []
    for rel, data in sorted(payload_files.items()):
        win = rel[len("payload/"):].replace("/", "\\")
        mpq_files.append({"slot": "patch-0.MPQ", "path": win, "from": "convert:" + rel, "sha256": sha(data)})
        if rel.endswith(".m2"):
            acceptance.append({"check": "mpq-has", "slot": "patch-0.MPQ", "path": win, "sha256": sha(data)})
    for e in dbc_edits:
        acceptance.append({"check": "dbc-cell", "slot": "patch-0.MPQ", "path": DBC_PATH, "row_id": e["row_id"], "column": e["column"], "type": "string", "equals": e["value"]})
    recipe = {
        "schema": "as-recipe/1", "id": a.id, "version": "0.1.0", "title": a.title, "description": a.description,
        "status": "experimental",
        "requires": {"game": {"exe_sha256": EXE_SHAS, "versions": ["0.103.0"]}, "tools": ["casc-export", f"gear-converter-{a.tag}", "mpq-packer"],
                     "disk_mb": 128},
        "sources": {"retail": retail,
                    "game-dbc": {"kind": "game-chain", "exclude_slots": ["patch-0.MPQ", "patch-1.MPQ"],
                                 "files": [{"path": DBC_PATH, "sha256": [OFFICIAL_DBC_SHA], "role": "official ItemDisplayInfo.dbc (v0.103.0 chain)"}]}},
        "steps": [
            {"id": "export", "op": "casc-export", "source": "retail"},
            {"id": "convert", "op": "run-tool", "tool": f"gear-converter-{a.tag}", "inputs": {"src": "export"},
             "expect_outputs": [{"path": rel, "sha256": sha(data)} for rel, data in sorted(payload_files.items())]},
            {"id": "base", "op": "game-extract", "source": "game-dbc"},
            {"id": "dbc", "op": "dbc-edit", "input": "base:DBFilesClient/ItemDisplayInfo.dbc", "output": "DBFilesClient/ItemDisplayInfo.dbc",
             "expect_input_sha256": OFFICIAL_DBC_SHA, "edits": dbc_edits, "expect_output_sha256": dbc_sha}],
        "outputs": {"mpq_files": mpq_files},
        "acceptance": acceptance,
        "provenance": f"Retail {mace_cat['version']} FileDataIDs listed in sources.retail.files; converter gear_step_{a.tag}.py sha256 {tool_sha}; "
                      "lab evidence analysis/runtime/lab-gear-* (Armory + combat captures).",
        "limits": ["Cosmetic only: ItemDisplayInfo model names change, no item stats.",
                   "Edits ItemDisplayInfo.dbc as a whole: combine with retail-mace-kultiras-silver only through a profile priority list "
                   "(this recipe already contains the row 5194 edit; the mace recipe still supplies that model's files)." if not a.no_mace else "",
                   "Static rigid models: particles, ribbons, lights and texture animations of the Retail originals are dropped.",
                   "One native display may be shared by several class starters, so the change shows on all of them."],
    }
    recipe["limits"] = [x for x in recipe["limits"] if x]
    out = RECIPES / f"{a.id}.json"
    out.write_text(json.dumps(recipe, indent=2) + "\n", encoding="utf8")
    snippet = {f"gear-converter-{a.tag}": {"script": script_path.name, "sha256": tool_sha, "search": ["tools", "../asset-coverage-gear"],
                                           "argv": ["--source-dir", "{in:src}", "--output-dir", "{out}", "--packer", "{tool:mpq-packer}"], "timeout": 600,
                                           "note": f"self-contained gear converter ({a.tag}); embeds rigid_item_convert + gear_batch + item spec"}}
    (META / f"registry-{a.tag}.json").write_text(json.dumps(snippet, indent=2) + "\n", encoding="utf8")
    summary = {"recipe": str(out), "tool": str(script_path), "tool_sha256": tool_sha, "payload_files": len(payload_files), "dbc_edits": len(dbc_edits),
               "dbc_sha256": dbc_sha, "casc_files": len(casc), "casc_bytes": sum(c["bytes"] for c in casc.values()),
               "mpq_payload_bytes": sum(len(d) for d in payload_files.values()), **totals}
    (META / f"{a.id}.summary.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf8")
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
